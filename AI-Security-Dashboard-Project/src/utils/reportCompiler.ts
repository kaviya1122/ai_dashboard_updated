import { Alert, ReportItem, ScanResult } from '../types';

/**
 * Compiles real security findings and alerts into a structured incident report
 * with a strictly enforced boundary between Telemetry/Evidence and AI recommendations.
 */
export function compileIncidentReport(params: {
  title: string;
  classification?: 'TLP:AMBER' | 'TLP:CLEAR' | 'TLP:GREEN' | 'TLP:RED';
  type?: 'executive_summary' | 'incident_triage' | 'threat_brief' | 'forensic_analysis';
  alerts: Alert[];
  scans: ScanResult[];
  analystConclusions?: string;
  aiCommentary?: string[];
}): ReportItem {
  const {
    title,
    classification = 'TLP:AMBER',
    type = 'incident_triage',
    alerts,
    scans,
    analystConclusions = 'Findings are based only on the supplied sample or uploaded data. Containment has not been verified.',
    aiCommentary = [],
  } = params;

  // Extract verifiable evidence items from alerts and scan findings
  const evidenceItems: ReportItem['evidenceItems'] = [];

  for (const alert of alerts) {
    for (const ev of alert.evidence) {
      evidenceItems.push({
        source: `Alert: ${alert.id} (${alert.affectedAsset})`,
        indicator: `${ev.key}: ${ev.value}`,
        severity: alert.severity,
        timestamp: alert.timestamp,
        verificationStatus: 'sample_data',
      });
    }
  }

  for (const scan of scans) {
    for (const rule of scan.rulesTriggered) {
      evidenceItems.push({
        source: `Scanner [${scan.scannerType.toUpperCase()}]: ${scan.id}`,
        indicator: `${rule.ruleName} (+${rule.points} pts) -> ${rule.description}`,
        severity: scan.severity,
        timestamp: scan.timestamp,
        verificationStatus: 'sample_data',
      });
    }
  }

  // Derive initial action items
  const actionItems: ReportItem['actionItems'] = [];
  if (alerts.some((a) => a.severity === 'critical')) {
    actionItems.push({
      action: 'Review host isolation in your endpoint or firewall product; this dashboard does not send the command',
      assignedTo: 'Not assigned',
      dueDate: new Date(Date.now() + 4 * 3600 * 1000).toISOString(),
      status: 'pending',
    });
  }

  actionItems.push({
    action: 'Consider preserving volatile memory and system event logs for forensic review',
    assignedTo: 'Not assigned',
    dueDate: new Date(Date.now() + 24 * 3600 * 1000).toISOString(),
    status: 'pending',
  });

  return {
    id: `REP-${Date.now().toString(36).toUpperCase()}`,
    title,
    classification,
    type,
    createdAt: new Date().toISOString(),
    author: 'Dashboard User',
    associatedAlertIds: alerts.map((a) => a.id),
    associatedScanIds: scans.map((s) => s.id),
    evidenceItems,
    aiAssistanceNotes: aiCommentary.length > 0 ? aiCommentary : [
      'DISCLAIMER: AI suggestions are decision-support heuristics, not authoritative legal verdicts. Analysts must verify raw telemetry.'
    ],
    analystConclusions,
    actionItems,
  };
}

/**
 * Generates exportable Markdown with explicit separation of evidence and AI advice
 */
export function renderReportToMarkdown(report: ReportItem): string {
  return `# ${report.title}
**Classification:** ${report.classification}  
**Report ID:** ${report.id}  
**Type:** ${report.type.replace('_', ' ').toUpperCase()}  
**Generated At:** ${new Date(report.createdAt).toUTCString()}  
**Author:** ${report.author}  

---

## 1. Executive Summary & Analyst Conclusions
${report.analystConclusions}

---

## 2. Hard Evidence & Telemetry Findings (Deterministic)
*Note: The following entries represent verifiable artifacts, system logs, and deterministic inspection rules.*

${
  report.evidenceItems.length === 0
    ? '_No direct evidence items attached._'
    : report.evidenceItems
        .map(
          (item, idx) =>
            `${idx + 1}. **[${item.severity.toUpperCase()}]** ${item.source}\n   - **Indicator:** \`${item.indicator}\`\n   - **Timestamp:** ${item.timestamp}\n   - **Verification:** ${item.verificationStatus}`
        )
        .join('\n\n')
}

---

## 3. AI Security Copilot Advisory (Non-Authoritative)
> **AI Operational Notice:** The suggestions below are generated by language model analysis for triage assistance. They must be validated against internal security policies before taking operational containment actions.

${
  report.aiAssistanceNotes.length === 0
    ? '_No AI notes recorded._'
    : report.aiAssistanceNotes.map((note) => `- ${note}`).join('\n')
}

---

## 4. Remediation & Action Items
| Action Item | Assigned To | Target SLA | Status |
| :--- | :--- | :--- | :--- |
${report.actionItems
  .map(
    (act) =>
      `| ${act.action} | ${act.assignedTo} | ${new Date(act.dueDate).toLocaleTimeString()} | ${act.status.replace('_', ' ').toUpperCase()} |`
  )
  .join('\n')}

---
*Report generated by AI Assisted Security Dashboard.*
`;
}
